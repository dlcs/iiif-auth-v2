using IIIFAuth2.Core.Data;
using IIIFAuth2.Core.Data.Entities;
using IIIFAuth2.Management.Features.Appointments.Models;
using IIIFAuth2.Management.Infrastructure.Requests;
using MediatR;
using Microsoft.EntityFrameworkCore;
using Npgsql;

namespace IIIFAuth2.Management.Features.Appointments.Requests;

/// <summary>
/// Create a new appointment with a server-generated token
/// </summary>
public record CreateAppointment(int CustomerId, AppointmentRequest Request)
    : IRequest<ModifyEntityResult<Appointment>>;

public class CreateAppointmentHandler(AuthServicesContext dbContext, AppointmentRules appointmentRules,
    ILogger<CreateAppointmentHandler> logger)
    : IRequestHandler<CreateAppointment, ModifyEntityResult<Appointment>>
{
    private const int MaxTokenAttempts = 3;

    public async Task<ModifyEntityResult<Appointment>> Handle(CreateAppointment request,
        CancellationToken cancellationToken)
    {
        var appointment = new Appointment { Customer = request.CustomerId }; // Id generated by EF on Add
        var error = await appointmentRules.ApplyAndValidate(appointment, request.Request, true, cancellationToken);
        if (error != null) return ModifyEntityResult<Appointment>.Failure(error, WriteResult.FailedValidation);

        dbContext.Appointments.Add(appointment);
        for (var attempt = 1; attempt <= MaxTokenAttempts; attempt++)
        {
            appointment.Token = AppointmentRules.GenerateToken();
            try
            {
                await dbContext.SaveChangesAsync(cancellationToken);
                logger.LogDebug("Created appointment {AppointmentId}", appointment.Id);
                return ModifyEntityResult<Appointment>.Success(appointment, WriteResult.Created);
            }
            catch (DbUpdateException ex) when (ex.InnerException is PostgresException
                                               {
                                                   SqlState: PostgresErrorCodes.UniqueViolation
                                               })
            {
                logger.LogWarning("Appointment token collision for customer {CustomerId} on attempt {Attempt}",
                    request.CustomerId, attempt);
            }
        }

        throw new InvalidOperationException(
            $"Unable to generate unique appointment token after {MaxTokenAttempts} attempts");
    }
}
